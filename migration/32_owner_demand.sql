--  32 — الطلب المكبوت: ما أراده اللاعبون ولم يجدوه
--
--  🔴 الرقم الوحيد في هذه القاعدة الذي لا يملكه أيّ منافس بلا تطبيق لاعبين
--  ────────────────────────────────────────────────────────────────────────
--  ترحيل 20 يسجّل «نبّهني إذا فضيت»: لاعبٌ أراد الخميس ٨ مساءً فوجدها محجوزة
--  فترك أثرًا. والصفوف موجودة منذ ذلك اليوم، **ولا يراها إلّا صاحبها والأدمن**
--  — أي أنّ الشخص الوحيد الذي يستطيع الفعل (يفتح ملعبًا · يرفع سعر تلك الساعة
--  · يُلغي إغلاقًا) هو الوحيد المحجوب عنها.
--
--  🔒 ولا تعبر هويّةُ أحد
--  ────────────────────
--  الصفّ في `slot_watch` يقول «فلانٌ يريد هذه الخانة» — وهذه معلومة عن **شخص**،
--  ولهذا مُنعت قراءتُه على المالك أصلًا وهو منعٌ صحيح يبقى كما هو. والعرض هنا
--  يُخرج **عددًا مجمَّعًا** لا صفًّا: لا `profile_id` ولا اسم ولا رقم — ولا
--  يستطيع أحدٌ أن يستخرجها منه، لأن ما ليس في العرض لا يخرج منه مهما كان
--  الاستعلام (نفس مبدأ `open_games` في ترحيل 22).
--
--  ⚠️ ولهذا **يبقى العرض `security definer`** (الافتراضي — بلا `security_invoker`):
--     لو كان `invoker` لقرأ المالكُ `slot_watch` بصلاحيته هو ⇒ صفر صفوف
--     (‏`sw_own` تحصرها في صفوفه) فيرى «لا طلب مكبوت» أبدًا، وهو عكس المطلوب
--     بالضبط. والحصرُ يقع **داخل** العرض بـ`owns_place`، لا في الواجهة.
--
--  ⚠️ ونافذةٌ من الطرفين: 120 يومًا للخلف (رغبةٌ من العام الماضي لا تصف الطلب
--     اليوم) و45 يومًا للأمام (نفس مدى `sbGetClosures` في التطبيق). فالعرض
--     يبقى صغيرًا بلا فهرسٍ جديد.
--
--  التشغيل: Supabase ← SQL Editor ← الصق ← Run.  آمن لإعادة التشغيل.
--  ولا يعتمد على شيء غير 20 (وهو يعتمد على 14) — ولا يكتب حرفًا في أيّ جدول.
-- ═══════════════════════════════════════════════════════════════════════════

do $$
begin
  if to_regclass('public.slot_watch') is null then
    raise exception 'يحتاج ترحيل 20 (نبّهني إذا فضيت) أولاً — لا مصدر للطلب المكبوت بدونه.';
  end if;
end $$;

begin;

-- ───────────────────────────────────────────────────────────────────────────
--  العرض — خمسة أعمدة، ولا سادس
--
--  `n` = كم شخصًا مختلفًا سجّل رغبته في هذه الخانة. والفهرس الفريد في ترحيل 20
--  (`slot_watch_uniq`) يضمن أنّ الشخص الواحد صفٌّ واحد ⇒ `count(*)` هو عدد
--  الأشخاص لا عدد الضغطات.
-- ───────────────────────────────────────────────────────────────────────────
drop view if exists public.place_slot_demand;
create view public.place_slot_demand as
  select f.place_id,
         sw.field_id,
         sw.watch_date,
         sw.hour,
         count(*)::int as n
    from public.slot_watch sw
    join public.fields f on f.id = sw.field_id
   where sw.watch_date >= (now() at time zone 'Asia/Amman')::date - 120
     and sw.watch_date <= (now() at time zone 'Asia/Amman')::date + 45
     -- 🔒 الحصر هنا لا في الواجهة: من ليس مالك المكان لا يخرج له صفّ
     and (public.is_admin() or public.owns_place(f.place_id))
   group by f.place_id, sw.field_id, sw.watch_date, sw.hour;

grant select on public.place_slot_demand to authenticated;

commit;

