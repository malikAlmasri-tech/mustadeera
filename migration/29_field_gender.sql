--  29 — لمن هذا الملعب: رجال · سيدات · مشترك
--
--  ما الذي يفعله هذا الملفّ فعلًا؟
--  ─────────────────────────────
--  يجعل **سياسة الجنس** بيانًا في القاعدة بدل أن تكون شيئًا يعرفه الناس
--  بالمكالمة. اليوم تصل لاعبةٌ إلى ملعبٍ لتكتشف أنه للرجال، أو يصل شابٌّ إلى
--  ساعةٍ محجوزة للسيدات — والتطبيق لا يملك ما يقوله لأيٍّ منهما. بعد هذا
--  الترحيل تُسجَّل السياسة على الملعب، ويعرضها التطبيق قبل الحجز ويصفّي بها.
--
--  🔹 لماذا على `fields` لا على `places`؟
--  ─────────────────────────────────────
--  نفس سبب `sport` في الترحيل 13 بالحرف: الوحدة القابلة للحجز هي **الملعب**،
--  ومجمّعٌ واحد قد يخصّص ملعبًا للسيدات ويترك الباقي مشتركًا. لو كانت على
--  المكان لاستحال تسجيله إلّا بتمزيقه إلى مكانين بنفس العنوان ونفس الهاتف.
--  وسياسة المكان تُشتقّ منه: «ما تقبله هذه المنشأة» = القيم المميّزة في ملاعبها.
--
--  🔴 لماذا `null` هي القيمة الافتراضية، ولماذا **ليست** 'mixed'؟
--  ────────────────────────────────────────────────────────────
--  الصفوف القائمة لم يقل عنها أحدٌ شيئًا. وكتابة 'mixed' عليها اختراعُ بيان
--  لم يُدلِ به صاحبه (م5): ملعبٌ للرجال فعلًا سيُعرَض «مشترك» فتذهب إليه
--  لاعبةٌ على وعدٍ لم يقطعه أحد — وهو ضررٌ حقيقي لا نقصُ ميزة. فالغياب يبقى
--  غيابًا: لا شارة تُعرَض، ولا يدخل الملعبُ نتيجةَ تصفيةٍ بجنسٍ بعينه.
--  و**الأدمن هو من يملأها** ملعبًا ملعبًا حين يعرف.
--
--  ⚠️ التطبيق يعمل بلا هذا الترحيل
--  ──────────────────────────────
--  العمود اختياري، والواجهة تسأل به ثمّ تسأل بدونه إن رُفض (نفس نمط
--  `fetchFields`/`SB_BK_EXTRA`)، فقبل تشغيله لا شارة ولا مرشِّح — وبعده
--  يظهر المرشِّح **فقط إن صرّح ملعبٌ واحد على الأقلّ**. لا خانة تصفيةٍ
--  فارغة تُعرَض على بياناتٍ لا تحملها.
--
--  التشغيل: Supabase ← SQL Editor ← الصق ← Run.  آمن لإعادة التشغيل.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.fields
  add column if not exists gender text;

do $$
begin
  -- المفردات مغلقة على مستوى القاعدة: `GENDERS` في app.js هو مصدر الحقيقة،
  -- وهذه نسخته. قيمةٌ رابعة تعني تعديل الاثنين معًا — وقيمةٌ تدخل القاعدة
  -- ولا تعرفها الواجهة **لا تُعرَض إطلاقًا**، فيقرأ اللاعب ملعبًا بلا سياسة
  -- وهو يحمل واحدة.
  if not exists (select 1 from pg_constraint where conname = 'fields_gender_chk') then
    alter table public.fields add constraint fields_gender_chk
      check (gender is null or gender in ('men','women','mixed'));
  end if;
end $$;

-- الفهرس جزئي على المصرَّح به وحده: الغالبية `null` اليوم، وفهرستها هدرٌ.
create index if not exists fields_gender_idx
  on public.fields(gender) where active and gender is not null;

-- ───────────────────────────────────────────────────────────────────────────
--  لا سياسة RLS جديدة، وهذا مقصود
--  ──────────────────────────────
--  `gender` عمودٌ في `fields`، و`fields_read` تسمح بقراءة الملاعب النشِطة
--  للجميع أصلًا (‏`/places` على الموقع مبنيّ عليها). والكتابة محكومة بما
--  يحكم بقيّة أعمدة `fields`: الأدمن ومالك المكان.
--
--  ⚠️ ولا يُشتقّ منه شيءٌ يخصّ **اللاعب**: لا حقل جنس في `profiles`، ولا
--  فحص «هل يجوز لهذا الحساب أن يحجز هذا الملعب؟». المنتج يقول **سياسة
--  المكان** ولا يصنّف مستخدميه — تصنيفُ الناس بيانٌ حسّاس يُجمَع بلا حاجة،
--  والمنع بناءً عليه قرارٌ لا يملكه تطبيقُ حجز بل إدارةُ الملعب عند البوّابة.
-- ───────────────────────────────────────────────────────────────────────────

