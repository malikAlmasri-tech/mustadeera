--  08 — بثّ سجلّ التدقيق حيًّا إلى /admin عبر Realtime
--
--  الغاية: أن تصل أحداث `audit_log` إلى لوحة الإدارة **وهي مفتوحة**، بلا
--  تحديث ولا استطلاع دوري. هذا آخر بند في المرحلة (و) من PLAN-2-website.md.
--
--  ⚠️ لماذا هذا الملفّ ضروري أصلًا:
--  ─────────────────────────────────
--  Realtime لا يبثّ إلّا الجداول المُدرَجة في النشر `supabase_realtime`.
--  والمصيدة أن الاشتراك بجدول **غير مُدرَج ينجح بلا أي خطأ** — الخادم يردّ
--  `status:"ok"` ويعطيك معرّف اشتراك، ثمّ لا يصل حدث واحد أبدًا.
--
--  مقيس هنا 2026-07-29: اشتراك بجدول اسمه `table_that_does_not_exist_xyz`
--  ردّ الخادمُ عليه `ok` مع معرّف. ⇒ **نجاح الاشتراك ليس دليلًا على شيء**،
--  ولا يجوز الاعتماد عليه كتحقّق.
--
--  الإشارة الصادقة هي رسالة `system` التي تلي الردّ. وقبل تشغيل هذا الملفّ
--  كانت (مقيسة حرفيًّا من متصفّح على القاعدة الحيّة 2026-07-29):
--
--    {"event":"system","payload":{"status":"error","extension":"postgres_changes",
--     "message":"Unable to subscribe to changes with given parameters. Please
--      check Realtime is enabled for the given connect parameters:
--      [event: INSERT, schema: public, table: audit_log, filters: [], select: nil]"}}
--
--  ⇒ الجدول **ليس** في النشر اليوم، وهذا الملفّ هو ما يُدخله. وبعد تشغيله
--  المفروض أن تصير الرسالة  status:"ok"  ونصّها «Subscribed to PostgreSQL».
--  واللوحة مبنيّة على هذا التمييز بالضبط: لا تصير النقطة خضراء إلّا بعده.
--
--  التشغيل: Supabase ← SQL Editor ← الصق ← Run.  آمن لإعادة التشغيل.
-- ═══════════════════════════════════════════════════════════════════════════

-- ① أدرِج الجدول في نشر Realtime (بلا خطأ إن كان مُدرَجًا سلفًا)
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename  = 'audit_log'
  ) then
    alter publication supabase_realtime add table public.audit_log;
  end if;
end $$;

-- ② لا نضبط REPLICA IDENTITY FULL — وهذا مقصود.
--    هي لازمة فقط لتسلّم الصفّ **القديم** في UPDATE/DELETE، واللوحة تشترك
--    بـINSERT وحده (سجلّ التدقيق لا يُعدَّل ولا يُحذَف أصلًا). وضبطها يضاعف
--    حجم الـWAL لجدول يكتب صفًّا مع كل حجز وتقييم ⇒ كلفة بلا مقابل.

-- ③ الأمان لم يتغيّر: السياسة القائمة تحكم البثّ أيضًا.
--    audit_admin ... for select using (public.is_admin())
--    Realtime يطبّق RLS على كل صفّ قبل إرساله ⇒ من ليس أدمن يشترك بنجاح
--    ولا يصله شيء. لا حاجة إلى سياسة جديدة.

-- ⚠️ ملاحظة خصوصية تستحقّ الوعي (لا إصلاحًا):
--    قراءة اللوحة عبر REST تنتقي خمسة أعمدة فقط، بينما Realtime يرسل الصفّ
--    **كاملًا** — ومنه `before`/`after` وفيهما لقطة الصفّ المتغيّر كلّه
--    (قد تحوي هاتفًا من reviews أو profiles). لا يمكن انتقاء أعمدة في
--    postgres_changes. وهذا مقبول لأن المستلم الوحيد هو الأدمن (RLS يضمنه)،
--    وهو صاحب المنصّة أصلًا. والصفحة **لا تعرض** هذين الحقلين عمدًا.

-- ─── تحقّق بعد التشغيل ─────────────────────────────────────────────────────
