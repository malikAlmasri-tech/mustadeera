--      select schemaname, tablename from pg_publication_tables
--      where pubname = 'supabase_realtime' order by tablename;
--    المفروض أن يظهر فيه سطر  public | audit_log
--
-- ② من الطرف الآخر: افتح /admin بحساب أدمن، وراقب نقطة الحالة بجانب عنوان
--    «سجلّ التدقيق». المفروض أن تصير خضراء ونصّها «حيّ». ثمّ نفّذ أي تغيير
--    يكتب في السجلّ (أنشئ حجزًا من التطبيق مثلًا) ⇒ يظهر السطر فورًا في
--    أعلى القائمة بلا تحديث الصفحة.
