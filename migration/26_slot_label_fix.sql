--  26 — تسميتان متطابقتان لخانتين مختلفتين: العاشرة صباحًا والعاشرة ليلًا
--
--  العطل
--  ─────
--  في `app.js` و`admin.html` و`build_import.mjs` و`RECIPES.sql` كانت الخانتان
--  تحملان **نفس السلسلة حرفًا بحرف**:
--
--      {label:'10:00 - 12:00 م', hour:10}   ← العاشرة صباحًا
--      {label:'10:00 - 12:00 م', hour:22}   ← العاشرة ليلًا
--
--  والهويّة بـ`hour` فالبيانات سليمة تمامًا — لا حجزٌ ذهب إلى الخانة الخطأ.
--  **المعروض وحده كان يكذب**: «حجوزاتي» ونافذة المراجعة ونصّ الإشعار ورسالة
--  الواتساب للمالك، أربعتها تطبع `time_label` كما هو، فلا شيء فيها يفرّق
--  صباحًا من ليل. ورجلٌ يصل الملعب العاشرة صباحًا وحجزه العاشرة مساءً.
--
--  ⚠️ والدرس أن **اللغة الأساسية وحدها كانت المعطوبة**: `enSlotLabel` تشتقّ
--     الإنجليزية من `startHour`/`endHour` فتخرج `10:00 AM - 12:00 PM` مقابل
--     `10:00 PM - 12:00 AM` — صحيحةً منذ البداية. ومن يفحص الإنجليزية وحدها
--     يمرّره. (نفس شكل مزلق «الشمسين» ومزلق تباين اللون في الثيم الواحد:
--     العطل الذي يظهر في نصف الحالات ينجو من نصف الفحوص.)
--
--  ما يفعله هذا الملفّ
--  ────────────────────
--  الكود أُصلح في مصادره الأربعة. وهذا الملفّ يُصلح **ما هو مكتوب في القاعدة
--  الآن**: تسميةُ الخانة داخل `fields.slots`، وتسميةُ الحجوزات **القادمة**
--  في `bookings.time_label`.
--
--  🔒 والحجوزات الماضية لا تُمَسّ عمدًا. `time_label` **لقطة** كما `price`:
--     هي ما قُرئ على الشاشة يوم وقع الاتّفاق، وتعديلُها بأثر رجعي يجعل السجلّ
--     يقول ما لم يُعرَض. والقادمة تُصلَح لأنها لم تُلعَب بعد، ولأن الالتباس
--     فيها ضررٌ لم يقع بعدُ ويمكن منعه.
--
--  مستقلّ تمامًا: لا يعتمد على أيّ ترحيل بعد 01.
--  التشغيل: Supabase ← SQL Editor ← الصق ← Run.  آمن لإعادة التشغيل.
-- ═══════════════════════════════════════════════════════════════════════════

begin;

-- ───────────────────────────────────────────────────────────────────────────
--  1) `fields.slots` — التسمية داخل المصفوفة
--
--  والمطابقة **على `h = 10` مع التسمية القديمة معًا** لا على التسمية وحدها:
--  الخانة 22 تحمل السلسلة نفسها وهي صحيحة، فمطابقةٌ نصّية عمياء كانت ستقلبها
--  إلى «10:00 ص - 12:00 م» — أي تصنع العطل المعاكس بدل أن تُصلح شيئًا.
-- ───────────────────────────────────────────────────────────────────────────
update public.fields f
   set slots = (
     select jsonb_agg(
              case when (e->>'h')::int = 10 and e->>'label' = '10:00 - 12:00 م'
                   then jsonb_set(e, '{label}', '"10:00 ص - 12:00 م"'::jsonb)
                   else e end
              order by (e->>'h')::int)
       from jsonb_array_elements(f.slots) e
   )
 where jsonb_typeof(f.slots) = 'array'
   and exists (
     select 1 from jsonb_array_elements(f.slots) e
      where (e->>'h')::int = 10 and e->>'label' = '10:00 - 12:00 م'
   );

-- ───────────────────────────────────────────────────────────────────────────
--  2) `bookings.time_label` — القادمة وحدها
-- ───────────────────────────────────────────────────────────────────────────
update public.bookings
   set time_label = '10:00 ص - 12:00 م'
 where hour = 10
   and time_label = '10:00 - 12:00 م'
   and booking_date >= (now() at time zone 'Asia/Amman')::date;

commit;

