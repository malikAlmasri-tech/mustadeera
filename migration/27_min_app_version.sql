--  27 — أدنى إصدار مقبول: المخطّط يتحرّك، والتطبيق على الهاتف لا
--
--  العطل البنيوي
--  ─────────────
--  `versionCode 1` · `versionName "1.0"` · توزيع APK مباشر بلا متجر ⇒ **لا
--  آلية تحديث إطلاقًا**، ولا فحص إصدار في الكود. بينما المخطّط يتحرّك في كل
--  ترحيل: أعمدة جديدة تُذكَر صراحةً في `select=`، مفردات مغلقة تتوسّع، دوالّ
--  تُضاف. ونسخةٌ قديمة على هاتف لاعبٍ تُظهر — في أحسن الأحوال — «الميزة غير
--  مُفعّلة»، وفي أسوئها **بيانات ناقصة تبدو سليمة**: قائمة حجوزات تحمّل
--  بالجولة الثالثة بلا `cancel_kind` فلا يرى صاحبها أنّ طلبه انقضت مهلته.
--
--  🔑 ولماذا `booking_rules` لا جدول جديد؟
--     لأنه **مقروء للجميع أصلًا** (‏`br_read using (true)` في 15) وموجود في
--     الجلبة نفسها. جدولٌ جديد لسطرٍ واحد يعني ترحيلًا وسياسةً ومنحًا وجلبةً
--     إضافية عند كل إقلاع — لأجل رقم.
--
--  🔒 وبوّابةٌ **ناصحة لا قاتلة**: `min_app_version` تعرض لوحًا يقول «نزّل
--     النسخة الجديدة» ويشير إلى `/download/`، ولا تُغلق التطبيق. إغلاقُ تطبيقٍ
--     يُوزَّع يدويًّا — بلا متجر يدفع التحديث — يترك اللاعبَ بلا شيء إن تعذّر
--     عليه التنزيل، وهو عقابٌ على عطلٍ ليس عطله. أمّا `block_app_version` فهي
--     الخطّ الأحمر: ما دونها **لا يُستعمل** لأنه يكتب بيانات خاطئة، لا لأنه
--     قديم. ويبقى صفرًا حتى يوجد سببٌ حقيقي.
--
--  ⚠️ والرقم المقارَن هو `versionCode` لا `versionName`: عددٌ صحيح يكبر أبدًا،
--     بينما «1.10» و«1.9» لا يترتّبان عدديًّا ولا نصّيًّا بالطريقة نفسها.
--     ومصدره في التطبيق `CONFIG.APP_BUILD`، **ونسخته في `android/app/build.gradle`
--     هي الأصل** — حارس المرآة `tools/check-mirrors.js` يقارنهما.
--
--  ⚠️ **بعد 15** (‏`booking_rules`).
--  التشغيل: Supabase ← SQL Editor ← الصق ← Run.  آمن لإعادة التشغيل.
-- ═══════════════════════════════════════════════════════════════════════════

begin;

insert into public.booking_rules(key, num_value, note) values
  ('min_app_version', 1,
   'أدنى versionCode لا يُنصَح بما دونه. التطبيق يعرض لوحًا يشير إلى /download/ ويبقى عاملًا. ارفعه بعد كل إصدار يضيف عمودًا أو دالّة يعتمد عليها مسارٌ أساسي'),
  ('block_app_version', 0,
   'الخطّ الأحمر: ما دون هذا الرقم يُمنَع من الحجز لأنه يكتب بيانات خاطئة. 0 = لا حظر. لا تُرفَع إلّا لسببٍ يُكتَب هنا')
on conflict (key) do nothing;

commit;

