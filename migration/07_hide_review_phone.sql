--  07 — إخفاء رقم هاتف المُقيِّم عن القراءة العامّة
--
--  🔴 عطل خصوصية حيّ (مُكتشَف ومقيس 2026-07-28)
--  ─────────────────────────────────────────────
--  السياسة الحالية:  create policy reviews_read on public.reviews
--                    for select using (true);
--  «true» تعني: أي أحد، بلا تسجيل دخول، يقرأ **كل أعمدة** الجدول — ومنها
--  `phone` و`author_name`. والمفتاح العام (anon) مضمَّن في الـAPK وفي صفحات
--  الموقع، والمستودع عامّ ⇒ أرقام هواتف كل من قيّم مكشوفة للجميع.
--
--  أُثبت بالقياس، لا بالقراءة:
--    curl -H "apikey: <anon>" ".../rest/v1/reviews?select=phone,author_name"
--    ⇒ أعاد أرقامًا حقيقية بلا أي مصادقة.
--
--  لماذا لا نكتفي بحذف العمود؟
--  ─────────────────────────────
--  التطبيق **يكتب** الرقم عند إرسال التقييم (app/native/app.js) ولا يقرأه
--  إطلاقًا. والرقم مفيد لك ولصاحب الملعب للتحقّق من تقييم مشبوه. فالصواب:
--  يبقى مخزّنًا، ويُمنع عن القراءة العامّة.
--
--  ⚠️ لماذا REVOKE على العمود وحده لا يكفي:
--  في Postgres صلاحية SELECT على مستوى **الجدول** تشمل كل الأعمدة، ولا
--  يُبطلها revoke على عمود. الطريقة الصحيحة: سحب صلاحية الجدول كاملةً ثم
--  منح الأعمدة المسموحة صراحةً — وهذا ما يفعله الملفّ.
--
--  التشغيل: Supabase ← SQL Editor ← الصق ← Run.  آمن لإعادة التشغيل.
-- ═══════════════════════════════════════════════════════════════════════════

-- ① اسحب صلاحية القراءة الشاملة عن الجدول
revoke select on public.reviews from anon, authenticated;

-- ② امنح الأعمدة العامّة وحدها (كل ما تعرضه الواجهة فعلًا)
grant select (id, legacy_id, created_at, place_id, field_id, author_name, rating, comment)
  on public.reviews to anon, authenticated;

-- ③ صاحب الملعب والأدمن يبقيان قادرَين على رؤية الرقم عند الحاجة.
--    (RLS يحصر الصفوف؛ وهذا المنح يفتح العمود لمن يملك الدور فقط.)
--    ملاحظة: الدور في Supabase واحد (`authenticated`) والتفريق يجري بـRLS،
--    فلا يمكن منح العمود لـ«المالك» وحده على مستوى الأعمدة. البديل الصحيح
--    لعرض الرقم للمالك: عرض (view) مقيّد بـowns_place — يُبنى عند الحاجة،
--    ولا شيء في الواجهة اليوم يعرضه.

-- ─── تحقّق بعد التشغيل ─────────────────────────────────────────────────────
-- المفروض أن يفشل هذا بخطأ صلاحية (وهذا هو المطلوب):
--   curl -H "apikey: <anon>" -H "Authorization: Bearer <anon>" \
--        "https://<ref>.supabase.co/rest/v1/reviews?select=phone"
-- والمفروض أن ينجح هذا:
--   curl ... "https://<ref>.supabase.co/rest/v1/reviews?select=author_name,rating,comment"
--
-- ⚠️ وانتبه: `select=*` من عميل مجهول سيفشل بعد هذا التغيير لأنه يطلب كل
--    الأعمدة ومنها `phone`. التطبيق لا يقرأ الجدول إطلاقًا (يكتب فقط)، لكن
--    إن أضفت لاحقًا قراءةً للتقييمات فاذكر الأعمدة صراحةً بدل `*`.
