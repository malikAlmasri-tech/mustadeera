begin;

-- ① **تسجيل حساب جديد كان سيفشل.** فعّلنا RLS على profiles وكتبنا سياسات
--    select/update فقط ولا سياسة insert ⇒ كل إدراج مرفوض، فلا يستطيع لاعب
--    جديد إنشاء ملفّه بعد التسجيل. يُسمح بالإدراج **لصاحب الحساب نفسه فقط**
--    (id = auth.uid())، أي لا يستطيع أحد إنشاء ملفّ باسم غيره.
create policy profiles_insert_self on public.profiles
  for insert with check (id = auth.uid());

-- ② **التقييم من زائر غير مسجّل كان سيفشل.** السياسة السابقة تشترط
--    auth.uid() is not null، بينما السلوك القائم في التطبيق يسمح للزائر
--    بالتقييم (نافذة التقييم تطلب الاسم والرقم ولا تطلب تسجيل دخول).
--    نُبقي السلوك كما هو حتى لا ينكسر مسار عامل، مع تقييد النطاق:
--    التقييم يجب أن يكون على **مكان نشط** وبقيمة صحيحة 1..5.
--    ⚠️ مقايضة معروفة: يبقى الباب مفتوحًا للتقييم الآلي المتكرّر. الحدّ منه
--       (إلزام تسجيل الدخول أو ربط التقييم بحجز فعليّ) قرار منتَج لا أمن بحت.
drop policy if exists reviews_insert on public.reviews;
create policy reviews_insert on public.reviews
  for insert with check (
    rating between 1 and 5
    and exists (select 1 from public.places p where p.id = place_id and p.active)
  );

commit;
