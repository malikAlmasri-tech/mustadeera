-- 30) إعادة بناء العرض `bookings_full` — الأعمدة الخمسة الغائبة عنه
--
-- 🔴 **العطل:** العرض مُعرَّف في `01_schema.sql` بـ`select b.*` — و`*` في تعريف
--    عرضٍ **تُفكّ عند الإنشاء لا عند القراءة**: Postgres يخزّن قائمة الأعمدة
--    كما كانت لحظتَئذ. فكلّ عمودٍ أضافه ترحيلٌ لاحق إلى جدول `bookings` بقي
--    **خارج العرض** بلا أن يفشل شيء ولا أن يقول أحدٌ شيئًا.
--
--    مقيس حيًّا بالمفتاح العام (2026-08-13):
--      bookings?select=no_show           ⇒ 200   (العمود موجود في الجدول)
--      bookings_full?select=no_show      ⇒ 42703 (وغائب عن العرض)
--    وكذلك: cancel_kind · visibility · players_needed · players_brought.
--
-- **وأثره ظاهرٌ للمستخدم**، لأن التطبيق يقرأ من العرض لا من الجدول:
--   • «حجوزاتي»: لا شارةَ مباراةٍ مفتوحة ولا زرَّ «إدارة المباراة»، ولا يُفرَّق
--     «انقضت المهلة» عن «رفض المالك» — والفرق هو **كلّ** ما بُني له ترحيل 15.
--   • لوحة المالك: لا زرَّ «لم يحضر» (ترحيل 16) ولا شارةَ مباراةٍ مفتوحة.
--   والتطبيق **لا يتعطّل**: `sbBookingsQuery` تسأل بالأعمدة ثمّ بلا أيٍّ منها
--   (ثلاث جولات)، فتنجح الجولة الأخيرة وتبدو الميزة «غير مُفعّلة» لا مكسورة.
--   ولهذا نجا العطل: `/admin` تقرأ `bookings` **خامًا** فتراها كلَّها.
--
-- ⚠️ **ولا يصلحه `create or replace view`**: أعمدة `b.*` الجديدة تُدرَج قبل
--    `place_name`/`city`/`field_name` ⇒ يتغيّر ترتيب أعمدة المخرَج، وPostgres
--    يرفض ذلك («cannot change name of view column»). فالحذف ثمّ الإنشاء.
--    ولا شيء يعتمد على هذا العرض (لا عرضَ آخر ولا دالّة) فالحذف آمن.
--
-- ⚠️ **وآمنٌ لإعادة التشغيل**، وآمنٌ على قاعدةٍ لم تُشغَّل عليها 15/16/22:
--    `b.*` تعطي ما هو موجود فعلًا، فالعرض يصف الجدول مهما كانت حالته.
--
-- ⚠️ و`security_invoker = on` **لازمة كما كانت**: بدونها يعمل العرض بصلاحيات
--    مالكه ⇒ يقرأ كلُّ لاعبٍ حجوزات الناس كلِّها. القيمة نفسها من 01 حرفيًّا.
-- ═══════════════════════════════════════════════════════════════════════════

drop view if exists public.bookings_full;

create view public.bookings_full with (security_invoker = on) as
  select b.*, p.name as place_name, p.city, f.name as field_name
  from public.bookings b
  join public.places p on p.id = b.place_id
  join public.fields f on f.id = b.field_id;

grant select on public.bookings_full to anon, authenticated;

