-- 33_booking_note.sql — ملاحظة اللاعب لصاحب الملعب
--
-- ما المشكلة التي يحلّها:
--   الحجز عندنا **طلبٌ ينتظر ردًّا**، والمالك يقرّر عليه من أربع حقائق:
--   الاسم والهاتف والملعب والساعة. وما لا يصله اليوم هو ما يقوله اللاعب عن
--   نفسه: «نحن عشرة ولازم صدريّات»، «ممكن نتأخّر ربع ساعة»، «بدنا كرتين».
--   وهي بالضبط المعلومات التي كانت تُقال في المكالمة التي جاء المنتج ليلغيها
--   — فسقطت في الطريق بلا بديل. النتيجة أنّ المالك يقبل ثمّ يتّصل ليسأل، أو
--   يقبل ولا يجهّز.
--
-- لماذا عمودٌ على `bookings` لا جدولٌ منفصل:
--   الملاحظة **صفةٌ للطلب** لا كيانٌ له عمر: تُكتب مرّةً مع الطلب، وتُقرأ مع
--   الطلب، وتموت معه. وجدولٌ لها يعني صلةً وقراءةً ثانية في كلّ مسار يقرأ
--   الحجوزات — ثمنٌ بلا مقابل.
--
-- ⚠️ القيود الثلاثة، ولكلٍّ سببه:
--   ① **سقف ٢٤٠ محرفًا** — الملاحظة سطران على بطاقةٍ في قائمة، لا رسالة. وبلا
--      سقفٍ في القاعدة يصير الحقل مساحةَ نصٍّ حرّ يكتبها عميلٌ معدَّل بميغابايت.
--      والسقف في القاعدة لا في الواجهة وحدها: `maxlength` يقترح ولا يمنع.
--   ② **لا تُعدَّل بعد الإرسال** — الملاحظة ما قاله اللاعب **لحظة الطلب**، وقد
--      يقرؤها المالك ويبني عليها قبوله. وتعديلُها بعده يجعل ما قُرئ غير ما هو
--      مكتوب. المُشغِّل يجمّدها على أي `update` من غير الأدمن.
--   ③ **لا يكتبها إلّا صاحب الحجز عند الإدراج** — المالك يقرأ ولا يكتب: سطرٌ
--      في فم اللاعب لم يقله. والحارس في المُشغِّل نفسه.
--
-- 🔴 وإعادةُ بناء `bookings_full` **إلزامية** ومكتوبةٌ هنا لا مؤجّلة:
--    `select b.*` تُفكّ عند إنشاء العرض لا عند قراءته ⇒ كلّ عمودٍ يضيفه ترحيلٌ
--    لاحق يبقى **في الجدول وخارج العرض** بلا خطأ ولا تحذير. وقد كلّف هذا
--    المشروعَ ثلاث دفعات (‏15/16/22) حتى أصلحه الترحيل 30، والقاعدة المكتوبة
--    في `CLAUDE.md` صريحة: **كلُّ ترحيلٍ يضيف عمودًا إلى `bookings` يعيد بناء
--    العرض معه**. والحذف ثمّ الإنشاء لا `create or replace` (ترتيب الأعمدة).
--
-- آمنٌ لإعادة التشغيل.
-- ═══════════════════════════════════════════════════════════════════════════

begin;

alter table public.bookings
  add column if not exists player_note text;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'bookings_note_len_chk') then
    alter table public.bookings
      add constraint bookings_note_len_chk
      check (player_note is null or char_length(player_note) <= 240);
  end if;
end $$;

comment on column public.bookings.player_note is
  'ملاحظة اللاعب لصاحب الملعب — تُكتب مرّة عند الإدراج ولا تُعدَّل بعدها (fn_booking_note_guard)';

-- ── الحارس: تُكتب مرّةً ولا تُعدَّل ──────────────────────────────────────────
-- ⚠️ **مُشغِّل لا `with check`**: تعبيرٌ في سياسة يردّ الخرق «صفًّا فارغًا مع
--    200» فلا يملك العميل رمزًا يقرؤه — نفس السبب الذي بُني له كلّ حارسٍ في
--    الترحيل 24. وهنا الإسناد **صامت** لا خطأ يُرفَع: التعديل ليس محاولةَ خرقٍ
--    يحتاج المستخدمُ أن يعرف سببها، بل حقلٌ لا قرار له فيه أصلًا.
create or replace function public.fn_booking_note_guard()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if public.is_admin() then return new; end if;

  if tg_op = 'INSERT' then
    -- المالك يُدخل حجزًا يدويًّا نيابةً عن لاعب اتّصل: لا ملاحظة «من اللاعب» هنا.
    if new.player_id is distinct from auth.uid() then
      new.player_note := null;
    end if;
    return new;
  end if;

  -- UPDATE: مهما أرسل الطرفان، تبقى القيمة الأصلية.
  new.player_note := old.player_note;
  return new;
end $$;

drop trigger if exists t_booking_note_guard on public.bookings;
-- الاسم `t_booking_note_guard` يقع بعد `t_booking_cancel_fields` أبجديًّا
-- (‏`c` قبل `n`) — ومُشغِّلات `before` تُطلَق بترتيب أسمائها. وهو الترتيب
-- الصحيح: حارس الإلغاء يعيد بناء الصفّ من `old` بـ`jsonb_populate_record`،
-- فلو سبقَنا لأعاد `player_note` القديمة على أي حال — والنتيجة واحدة، لكنّ
-- الاعتماد على مصادفةٍ في حارسٍ كُتب لغرضٍ آخر هو المزلق المسجَّل في
-- `CLAUDE.md` حرفيًّا. فالشرط مكتوبٌ هنا صراحةً ولا يتّكل على جاره.
create trigger t_booking_note_guard
  before insert or update on public.bookings
  for each row execute function public.fn_booking_note_guard();

-- ── إعادة بناء العرض (إلزامية — انظر الرأس) ────────────────────────────────
-- ⚠️ **نسخةٌ حرفية من تعريف الترحيل 30** — لا صياغة جديدة: أيّ اختلافٍ هنا
--    (اسم عمود · قائمة `grant` · `security_invoker`) يصير فرقًا صامتًا بين
--    قاعدةٍ شُغِّل عليها 30 وأخرى شُغِّل عليها 33، وهو أسوأ من غياب العرض.
drop view if exists public.bookings_full;
create view public.bookings_full with (security_invoker = on) as
  select b.*, p.name as place_name, p.city, f.name as field_name
  from public.bookings b
  join public.places p on p.id = b.place_id
  join public.fields f on f.id = b.field_id;

grant select on public.bookings_full to anon, authenticated;

commit;

-- ═══ التحقّق بعد التشغيل (بالمفتاح العام + توكن لاعب) ═══════════════════════
--   ① العمود في العرض لا في الجدول وحده — وهو الفحص الذي كان يسقط ثلاث دفعات:
--        GET /rest/v1/bookings_full?select=player_note&limit=0   ⇒ 200
--      (‏400 مع `42703` تعني أنّ إعادة بناء العرض لم تقع.)
--   ② السقف مفروضٌ في القاعدة لا في الواجهة:
--        POST /rest/v1/bookings  {... "player_note": <٢٤١ محرفًا>}  ⇒ 400 / 23514
--   ③ التجميد بعد الإرسال:
--        PATCH /rest/v1/bookings?id=eq.<حجزي>  {"player_note":"x"}  ⇒ 200
--        ثمّ GET على نفس الصفّ ⇒ القيمة **لم تتغيّر**.
--      ⚠️ ولا تُقرأ «200» نجاحًا هنا: الحارس يُسند صامتًا، والدليل هو القراءة
--         بعده لا رمزُ الاستجابة — نفس درس «قبول العملية ≠ نجاحها».
