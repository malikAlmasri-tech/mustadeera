-- ═══════════════════════════════════════════════════════════════════════════
--  تنظيف: إسقاط التقييمات المُختلقة `rating_seed` / `reviews_seed`
--  (البند 6 في PLAN-1-completion.md — قرار المستخدم رقم 4: التقييمات الحقيقية فقط)
--
--  ⚠️ هذا الملفّ **اختياري وغير عاجل**. التطبيق توقّف عن قراءة العمودين أصلًا
--     (app/native/app.js — دالة sbPlace)، فالمستخدم لم يعد يرى أي رقم مُختلق
--     سواء شُغِّل هذا الملفّ أم لا. تشغيله مجرّد تنظيف للقاعدة.
--
--  ─── ما هما ────────────────────────────────────────────────────────────────
--  في الشيت القديم كُتبت تقييمات يدويًّا (4.8 من 120 تقييمًا، 4.6 من 80 …)
--  لكل مكان، بينما التقييمات الحقيقية في `public.reviews` **ستّة فقط**.
--  نُقلا كما هما أثناء الاستيراد حفاظًا على السلوك القائم، ثم أُسقطا.
--
--  ─── الأثر بعد التشغيل ─────────────────────────────────────────────────────
--  مكان له تقييمات حقيقية  ⇒ يعرض متوسّطها وعددها من العرض `place_stats`.
--  مكان بلا تقييم حقيقي     ⇒ **لا تُعرض له شارة نجمة إطلاقًا** (لا «0 (0)»).
--
--  ⚠️ غير قابل للتراجع: الأرقام المكتوبة يدويًّا تُفقد نهائيًّا. وهذا مقصود —
--     لا مكان في المنتج لرقم لم يكتبه لاعب حقيقي (قاعدة الصدق م5).
--
--  ملاحظة: `02_import.sql` ما زال يُنشئ العمودين (`add column if not exists`)
--  حفاظًا على أمانة الاستيراد من المصدر. فإن أُعيد الاستيراد يومًا، يُشغَّل
--  هذا الملفّ بعده مرّة أخرى. آمن التكرار.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.places drop column if exists rating_seed;
alter table public.places drop column if exists reviews_seed;

-- ─── تحقّق ذاتي: يرفع خطأ إن بقي أحد العمودين ───────────────────────────────
do $$
declare n int;
begin
  select count(*) into n
    from information_schema.columns
   where table_schema = 'public' and table_name = 'places'
     and column_name in ('rating_seed', 'reviews_seed');

  if n > 0 then
    raise exception 'ما زال % من عمودَي البذرة موجودًا في public.places', n;
  end if;

  raise notice '✅ أُسقط rating_seed و reviews_seed. التقييمات المعروضة كلّها حقيقية الآن.';
end $$;
